#!/usr/bin/env python3
"""The licence notices of every crate this repository ships (#155).

The static library and the CLI link their dependencies in, and the MIT
licence most of them carry asks that "the above copyright notice and this
permission notice shall be included in all copies or substantial portions of
the Software"; Apache-2.0 asks for a copy of the licence. A shipped artifact
is such a copy, so it carries THIRD-PARTY-LICENSES.md beside LICENSE.

  third-party-notices.py generate   rewrite THIRD-PARTY-LICENSES.md
  third-party-notices.py check      fail when a shipped crate has no section

The crates are the normal dependencies (not dev, not build) of this crate
with every feature a shipped artifact enables (`cli,write`), from
`cargo metadata`, which resolves without building. A crate's notice is its
own licence file, the MIT one where it offers a choice (the shortest
obligation); a crate that ships no licence file gets its licence's standard
text over the authors its manifest names. Sections are keyed by crate name,
so a version bump does not stale the file; a new crate does.
"""
import glob
import json
import os
import subprocess
import sys

OUT = "THIRD-PARTY-LICENSES.md"
FEATURES = "cli,write"

MIT = """Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
"""


def shipped():
    m = json.loads(subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--features", FEATURES],
        capture_output=True, text=True, check=True).stdout)
    pkgs = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    root = m["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    seen.discard(root)
    return sorted((pkgs[i] for i in seen), key=lambda p: p["name"])


def notice(p):
    """(file name or None, text) of a crate's licence notice."""
    d = os.path.dirname(p["manifest_path"])
    files = sorted(os.path.basename(f) for f in glob.glob(os.path.join(d, "*"))
                   if os.path.basename(f).upper().startswith(("LICEN", "COPYING")))
    for prefer in ("LICENSE-MIT", "LICENSE.MIT", "LICENSE"):
        for f in files:
            if f.upper().split(".")[0] == prefer.upper().split(".")[0] and (prefer != "LICENSE" or f.upper() in ("LICENSE", "LICENSE.TXT", "LICENSE.MD")):
                return f, open(os.path.join(d, f), errors="replace").read().strip() + "\n"
    if files:
        f = files[0]
        return f, open(os.path.join(d, f), errors="replace").read().strip() + "\n"
    if "MIT" in (p.get("license") or ""):
        authors = ", ".join(a.split(" <")[0] for a in p.get("authors") or []) or "the authors of " + p["name"]
        return None, f"Copyright (c) {authors}\n\n{MIT}"
    sys.exit(f"third-party-notices: {p['name']} ships no licence file and is not MIT-licensed; "
             "write its notice by hand")


def generate():
    parts = [
        "# Third-party licences",
        "",
        "This repository's static library and command-line tools contain code from",
        "the crates below, each under its own licence. Their notices follow, as",
        "those licences require. Generated by `scripts/third-party-notices.py",
        "generate` from `cargo metadata`; `chore lint` checks every shipped crate",
        "has one.",
        "",
    ]
    for p in shipped():
        f, text = notice(p)
        parts += [f"## {p['name']}", "",
                  f"{p['name']} {p['version']}, licensed {p.get('license') or 'see below'}"
                  + (f" ({p['repository']})" if p.get("repository") else "") + ".",
                  "This notice is " + (f"its `{f}`." if f else "its licence's standard text over the authors its manifest names, since the crate ships no licence file."),
                  "", "```text", text.rstrip("\n"), "```", ""]
    with open(OUT, "w") as fh:
        fh.write("\n".join(parts))
    print(f"third-party-notices: {OUT} written")


def check():
    if not os.path.isfile(OUT):
        print(f"third-party-notices: there is no {OUT}: the shipped artifacts carry no notices for "
              "the crates they link (`scripts/third-party-notices.py generate`)", file=sys.stderr)
        return 1
    have = {l[3:].strip() for l in open(OUT) if l.startswith("## ")}
    missing = [p["name"] for p in shipped() if p["name"] not in have]
    if missing:
        print(f"third-party-notices: {OUT} has no notice for: {', '.join(missing)} "
              "(`scripts/third-party-notices.py generate`)", file=sys.stderr)
        return 1
    print(f"third-party-notices: every shipped crate has its notice in {OUT}")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1:2]
    if cmd == ["generate"]:
        generate()
    elif cmd == ["check"]:
        sys.exit(check())
    else:
        sys.exit(__doc__)
